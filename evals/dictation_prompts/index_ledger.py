#!/usr/bin/env python3
"""Regenerate the Run Ledger's index.

Usage:
  ./index_ledger.py

Every row is read out of the runs themselves — their manifests and their score
files — so the index cannot drift from what the ledger holds. It is a browsable
table, not a source of truth: delete it and this command rebuilds it.
"""

import sys

from ledger import JUDGE_FILES, LEDGER, ScoredRun

INDEX = LEDGER / "index.md"

HEADER = """\
# Run Ledger

Every Eval Run recorded here, newest last. Generated by `./index_ledger.py` —
do not edit by hand; run the command instead.

`word` and `punct` are Deterministic Scores, means over the run's cases. The two
judge columns are Judge Score overall means, one per reading: `blind` never saw
the case's reference, `anchored` scored deductions away from it. Each holds only
within the judge named beside it, so no judge column is ever read against another
judge's column, against the other mode, or against `word`.

A mean that names a case count — `0.986 (claude-opus-5, 21/28 cases)` — was taken
over that many of the run's cases and not the rest, so it is not a reading of the
whole run and does not compare with one. A run the axis read none of holds no mean
and prints `—`.
"""

COLUMNS = [
    "run",
    "recorded",
    "eval set",
    "cases",
    "model",
    "prompt",
    "runtime",
    "word",
    "punct",
    "loss",
    "inv",
    "judge blind",
    "judge anchored",
]

MISSING = "—"


def mean_cell(value, scores, note=None):
    """One mean, and what has to be read with it.

    A run with no mean on the axis reads as unscored: an axis that read none of
    the run's cases holds no number, and printing the absence as a value would put
    a run nobody scored in the same column as the runs somebody did. A mean over
    part of a run carries the part, because a mean over 21 of 28 cases answers a
    different question from a mean over all 28 and would otherwise print as though
    it were the same reading.
    """
    if value is None:
        return MISSING
    marks = [note] if note else []
    if scores.partial:
        marks.append("{scored}/{of} cases".format(**scores.coverage))
    return f"{value} ({', '.join(marks)})" if marks else str(value)


def deterministic_columns(run):
    if run.deterministic is None:
        return [MISSING] * 4
    scores = run.deterministic
    return [
        mean_cell(scores.summary["word_score_mean"], scores),
        mean_cell(scores.summary["punctuation_score_mean"], scores),
        scores.summary["content_loss"],
        scores.summary["invented"],
    ]


def judge_columns(run):
    """One column per judge mode: a blind mean and an anchored mean are different
    measurements, so neither stands in for the other where it is missing."""
    columns = []
    for mode in JUDGE_FILES:
        scores = run.judges.get(mode)
        columns.append(
            MISSING if scores is None
            else mean_cell(
                scores.summary["overall_mean"], scores, scores.summary["judge"]["model"]
            )
        )
    return columns


def row(run):
    return [
        run.run_id,
        run.manifest["recorded_at"],
        run.eval_set["name"],
        run.eval_set["case_count"],
        run.arm["model"],
        run.arm["prompt_name"],
        run.arm["runtime"],
        *deterministic_columns(run),
        *judge_columns(run),
    ]


def runs():
    return [
        ScoredRun(directory)
        for directory in sorted(LEDGER.iterdir())
        if (directory / "manifest.json").exists()
    ]


def index(runs):
    rows = sorted(runs, key=lambda run: run.manifest["recorded_at"])
    table = [f"| {' | '.join(COLUMNS)} |", f"|{'---|' * len(COLUMNS)}"]
    table += [f"| {' | '.join(str(cell) for cell in row(run))} |" for run in rows]
    return "\n".join([HEADER, *table, ""])


def main():
    recorded = runs()
    INDEX.write_text(index(recorded))
    print(f"Indexed {len(recorded)} runs: {INDEX}")


if __name__ == "__main__":
    sys.exit(main())
